// Regenerate the mobile monogram's compatible outlines from the shipped OFL fonts.
// No font parser ships to the browser. Run from the repository root with Node.
import { openSync } from 'fontkit'
import { mkdirSync, writeFileSync } from 'node:fs'

const font = (weight) => openSync(`public/fonts/PlayfairDisplay-Latin-${weight}.woff2`)
const bold = font('700'),
  italic = font('700-Italic'),
  regular = font('400')
function contours(font, character) {
  const result = []
  let points = [],
    current = [0, 0]
  const add = (x, y) => {
    current = [x, y]
    points.push([x / font.unitsPerEm, -y / font.unitsPerEm])
  }
  for (const { command, args: a } of font.glyphForCodePoint(character.codePointAt(0)).path
    .commands) {
    if (command === 'moveTo') {
      points = []
      result.push(points)
      add(...a)
    } else if (command === 'lineTo') add(...a)
    else if (command === 'closePath') continue
    else {
      const [x, y] = current
      for (let i = 1; i <= 16; i++) {
        const t = i / 16,
          u = 1 - t
        if (command === 'quadraticCurveTo')
          add(
            u * u * x + 2 * u * t * a[0] + t * t * a[2],
            u * u * y + 2 * u * t * a[1] + t * t * a[3],
          )
        else
          add(
            u * u * u * x + 3 * u * u * t * a[0] + 3 * u * t * t * a[2] + t * t * t * a[4],
            u * u * u * y + 3 * u * u * t * a[1] + 3 * u * t * t * a[3] + t * t * t * a[5],
          )
      }
    }
  }
  return result.sort((a, b) => Math.abs(area(b)) - Math.abs(area(a)))
}
function area(points) {
  return points.reduce((sum, [x, y], i) => {
    const next = points[(i + 1) % points.length]
    return sum + x * next[1] - next[0] * y
  }, 0)
}
function sample(points, count) {
  const lengths = points.map(([x, y], i) =>
    Math.hypot(points[(i + 1) % points.length][0] - x, points[(i + 1) % points.length][1] - y),
  )
  const total = lengths.reduce((a, b) => a + b, 0)
  let edge = 0,
    traversed = 0
  return Array.from({ length: count }, (_, i) => {
    const distance = (i * total) / count
    while (edge < lengths.length - 1 && traversed + lengths[edge] < distance)
      traversed += lengths[edge++]
    const p = points[edge],
      q = points[(edge + 1) % points.length],
      t = (distance - traversed) / (lengths[edge] || 1)
    return [p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t]
  })
}
function align(source, target) {
  if (area(source) * area(target) < 0) target.reverse()
  let best = 0,
    score = Infinity
  for (let shift = 0; shift < target.length; shift++) {
    const cost = source.reduce((sum, p, i) => {
      const q = target[(i + shift) % target.length]
      return sum + (p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2
    }, 0)
    if (cost < score) {
      best = shift
      score = cost
    }
  }
  return target.map((_, i) => target[(i + best) % target.length])
}
function pair(sourceFont, sourceChar, targetChar) {
  const from = contours(sourceFont, sourceChar),
    to = contours(regular, targetChar)
  return from.map((contour, index) => {
    const count = index === 0 ? 128 : 48,
      source = sample(contour, count)
    // A disappearing ampersand counter closes inside the N's left stem.
    const target = to[index]
      ? align(source, sample(to[index], count))
      : Array.from({ length: count }, () => [0.075, -0.35])
    return source.map(([x, y], point) => [x, y, ...target[point]].map((value) => +value.toFixed(5)))
  })
}
const glyphs = [pair(bold, 'B', 'B'), pair(italic, '&', 'N'), pair(bold, 'B', 'B')]
const output = 'modules/public-web/src/ui/logos/monogramPaths.ts'
mkdirSync('modules/public-web/src/ui/logos', { recursive: true })
writeFileSync(
  output,
  `// Generated by tools/brand/morph-paths.mjs from the shipped Playfair Display fonts.\n// Font outlines: SIL Open Font License; see public/fonts/PLAYFAIR-DISPLAY-OFL.txt.\nexport const monogramPaths = ${JSON.stringify(glyphs)} as const\n`,
)
